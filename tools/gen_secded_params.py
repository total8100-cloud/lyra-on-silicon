"""Generate the SECDED-encoded codeword for a compiled Lyra theta, as a Verilog
localparam header, for use by tb/tb_zone_isolation_secded.v.

Codeword bit convention (must match rtl/secded_decoder.v exactly):
  codeword[20:0]  = Hamming word positions 1..21 (codeword[i] = word[i+1])
  codeword[21]    = overall parity bit p0
i.e. a single 22-bit vector CODEWORD[21:0], CODEWORD[21]=p0, CODEWORD[20:0]=word bits.

Target: Cyber domain, zone_isolation (IEC 62443-3-3 SR 5.2), theta=0.30,
Q4.12 fixed point (16-bit, 12 fractional bits) -- same format validated in
pilot/lyra_secded_mitigation.py.

Usage: python tools/gen_secded_params.py > rtl/zone_isolation_params.vh
"""
import numpy as np

K, FRAC_BITS = 16, 12
THETA_TRUE = 0.30


def hamming_params(k):
    m = 1
    while (2 ** m) < (k + m + 1):
        m += 1
    return m


def encode_secded(data_bits, k, m):
    n = k + m
    word = {}
    data_iter = iter(data_bits)
    for pos in range(1, n + 1):
        if (pos & (pos - 1)) == 0:
            word[pos] = 0
        else:
            word[pos] = next(data_iter)
    for p_pos in [1 << i for i in range(m)]:
        parity = 0
        for pos in range(1, n + 1):
            if pos == p_pos:
                continue
            if pos & p_pos:
                parity ^= word[pos]
        word[p_pos] = parity
    p0 = 0
    for pos in range(1, n + 1):
        p0 ^= word[pos]
    return word, p0, n


def int_to_bits(q, total_bits):
    u = q & ((1 << total_bits) - 1)
    return [(u >> i) & 1 for i in range(total_bits)]


def quantize(val, frac_bits, total_bits):
    scale = 2 ** frac_bits
    qmax = 2 ** (total_bits - 1) - 1
    q = int(np.clip(round(val * scale), -qmax - 1, qmax))
    return q, scale


m = hamming_params(K)
q_theta, scale = quantize(THETA_TRUE, FRAC_BITS, K)
data_bits = int_to_bits(q_theta, K)
word, p0, n = encode_secded(data_bits, K, m)

codeword = 0
for pos in range(1, n + 1):
    if word[pos]:
        codeword |= (1 << (pos - 1))
if p0:
    codeword |= (1 << n)

print(f"// Auto-generated by tools/gen_secded_params.py -- do not edit by hand.")
print(f"// theta_true={THETA_TRUE}, K={K}, FRAC_BITS={FRAC_BITS}, m={m}, n={n} "
      f"(codeword width = n+1 = {n+1})")
print(f"localparam THETA_Q         = 16'sd{q_theta};  // q_theta (reference, uncoded)")
print(f"localparam [{n}:0] THETA_CODEWORD = {n+1}'b{codeword:0{n+1}b};")
print(f"// bit layout: THETA_CODEWORD[{n-1}:0] = Hamming word positions 1..{n} ; "
      f"THETA_CODEWORD[{n}] = overall parity p0")
